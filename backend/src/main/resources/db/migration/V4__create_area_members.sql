CREATE TABLE area_members
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    finance_area_id  BIGINT      NOT NULL,
    user_id          BIGINT      NOT NULL,

    role             VARCHAR(20) NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    joined_at        TIMESTAMP   NOT NULL,
    removed_at       TIMESTAMP,

    created_by       BIGINT      NOT NULL,
    updated_by       BIGINT      NOT NULL,

    created_at       TIMESTAMP   NOT NULL,
    updated_at       TIMESTAMP   NOT NULL,

    CONSTRAINT fk_area_members_finance_area
        FOREIGN KEY (finance_area_id)
            REFERENCES finance_areas(id),

    CONSTRAINT fk_area_members_user
        FOREIGN KEY (user_id)
            REFERENCES users(id),

    CONSTRAINT fk_area_members_created_by
        FOREIGN KEY (created_by)
            REFERENCES users(id),

    CONSTRAINT fk_area_members_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users(id),

    CONSTRAINT uq_area_members_area_user
        UNIQUE (finance_area_id, user_id)
);

CREATE INDEX idx_area_members_user_id
    ON area_members(user_id);

CREATE INDEX idx_area_members_finance_area_id
    ON area_members(finance_area_id);