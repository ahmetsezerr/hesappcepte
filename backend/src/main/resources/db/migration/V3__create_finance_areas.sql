CREATE TABLE finance_areas
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(80) NOT NULL,
    area_type        VARCHAR(20) NOT NULL,
    sharing_type     VARCHAR(20) NOT NULL,
    base_currency    VARCHAR(3)  NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_by       BIGINT      NOT NULL,
    updated_by       BIGINT      NOT NULL,

    created_at       TIMESTAMP   NOT NULL,
    updated_at       TIMESTAMP   NOT NULL,

    CONSTRAINT fk_finance_areas_created_by
        FOREIGN KEY (created_by)
            REFERENCES users(id),

    CONSTRAINT fk_finance_areas_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES users(id)
);

CREATE INDEX idx_finance_areas_created_by
    ON finance_areas(created_by);